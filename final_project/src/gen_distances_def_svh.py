"""
  DESCRIPTION:
    This file is used to generate a system verilog header file which 
    defines a distance to in polar coordintes and provides SIN_LUT as a
    rom storing sin(theta) * MAX_POSSITIVE_POWER_OF_2_DISTANCE (for easy "division" via bitshifts)
""" """
  USAGE: gen_distances_def_svh.py [DIST_WIDTH] [ANGLE_WIDTH] > [distances_def_svh_file]
    DIST_WIDTH:   number of bits in a distance (current default 12)
    ANGLE_WIDTH:  number of bits in an angle (current default 8)
"""
import math, sys
DIST_WIDTH                        = int(sys.argv[1]) if len(sys.argv) > 1 else 12
ANGLE_WIDTH                       = int(sys.argv[2]) if len(sys.argv) > 2 else 8
N_ANGLES                          = 1 << ANGLE_WIDTH
MAX_POSSITIVE_POWER_OF_2_DISTANCE = 1 << (DIST_WIDTH - 2)

vals = [round(math.sin(2 * math.pi * i / N_ANGLES) * MAX_POSSITIVE_POWER_OF_2_DISTANCE) for i in range(N_ANGLES)]
assert all(-MAX_POSSITIVE_POWER_OF_2_DISTANCE <= v <= MAX_POSSITIVE_POWER_OF_2_DISTANCE for v in vals)

print("// Generated by gen_distances_def_svh.py - do not edit")
print("/* verilator lint_off UNUSEDPARAM */")
print(f"// {N_ANGLES} entries = one full turn, value = round(sin(2*pi*i/{N_ANGLES}) * {MAX_POSSITIVE_POWER_OF_2_DISTANCE})")
print(f"// cos(i) == SIN_LUT[(i + {N_ANGLES // 4}) % {N_ANGLES}]")
print(f"localparam  int ANGLE_WIDTH  = {ANGLE_WIDTH};")
print(f"localparam  int DIST_WIDTH   = {DIST_WIDTH};")
print(f"localparam  int UNIT_SHIFT   = {DIST_WIDTH - 2}; // corresponds to max possitive power of 2")
print(f"typedef     logic signed    [ DIST_WIDTH    - 1 : 0 ]   dist_t;")
print(f"typedef     logic signed    [ 2*DIST_WIDTH  + 1 : 0 ]   dot_t;")
print(f"typedef     logic signed    [ 2*DIST_WIDTH      : 0 ]   det_t;")
print(f"typedef     logic           [ ANGLE_WIDTH   - 1 : 0 ]   angle_t;")
print(f"localparam  angle_t                                     PI          = angle_t'( 1 << ( ANGLE_WIDTH - 1 ) );")
print(f"localparam  angle_t                                     HALF_PI     = angle_t'( 1 << ( ANGLE_WIDTH - 2 ) );")
print(f"localparam  dist_t SIN_LUT [0:{N_ANGLES - 1}] = '{{ {DIST_WIDTH}'sd{vals[0]}")
for i in range(1, N_ANGLES):
    if (vals[i] >= 0): 
      print(f", {DIST_WIDTH}'sd{vals[i]}")
    else:
      print(f", -{DIST_WIDTH}'sd{-vals[i]}")
print("};")
print(f"function automatic dist_t sin(angle_t angle);")
print(f"  return SIN_LUT[ angle ];")
print(f"endfunction")
print(f"function automatic dist_t cos(angle_t angle);")
print(f"  return SIN_LUT[ angle + HALF_PI ];")
print(f"endfunction")
print(f"function automatic dist_t sinp(angle_t angle, dist_t dist);")
print(f"  return (dist * sin(angle)) >>> UNIT_SHIFT;")
print(f"endfunction")
print(f"function automatic dist_t cosp(angle_t angle, dist_t dist);")
print(f"  return (dist * cos(angle)) >>> UNIT_SHIFT;")
print(f"endfunction")
