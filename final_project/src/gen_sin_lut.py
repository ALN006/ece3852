"""Generate sin_lut.svh: full-wave sine table, integer only at runtime.

usage: gen_sin_lut.py [ANGLE_BITS] [AMP_BITS] > sin_lut.svh
  ANGLE_BITS: table has 2**ANGLE_BITS entries, one full turn (default 8)
  AMP_BITS:   signed output width; amplitude is 2**(AMP_BITS-2) (default 16)
"""
import math, sys

angle_bits = int(sys.argv[1]) if len(sys.argv) > 1 else 8
amp_bits   = int(sys.argv[2]) if len(sys.argv) > 2 else 16
n     = 1 << angle_bits
scale = 1 << (amp_bits - 2)           # 1.0 == scale

vals = [round(math.sin(2 * math.pi * i / n) * scale) for i in range(n)]
assert all(-(1 << (amp_bits - 1)) <= v < (1 << (amp_bits - 1)) for v in vals)

print("// Generated by gen_sin_lut.py - do not edit")
print(f"// {n} entries = one full turn, value = round(sin(2*pi*i/{n}) * {scale})")
print(f"// cos(i) == SIN_LUT[(i + {n // 4}) % {n}]")
print(f"localparam int SIN_ANGLE_BITS = {angle_bits};")
print(f"localparam int SIN_AMP_BITS   = {amp_bits};")
print(f"localparam int SIN_ONE        = {scale};")
print(f"localparam logic signed [{amp_bits - 1}:0] SIN_LUT [0:{n - 1}] = '{{")
for i in range(0, n, 8):
    row = ", ".join(f"{amp_bits}'sd{v}" if v >= 0 else f"-{amp_bits}'sd{-v}"
                    for v in vals[i:i + 8])
    print("    " + row + ("," if i + 8 < n else ""))
print("};")